"""E26 table on Paderborn: fault-order rule, band choice and acquisition.

Project rule: the table comes from the experiment's ``analysis.json`` files, never from a
transcribed number.

- **Sources,** all from the raw stream:
  - `E26/results-paderborn/analysis.json`: the blind kurtogram;
  - `E26/results-paderborn-rule/analysis.json`: E26b, with the rule fixed and the band changing;
  - `E26/results-paderborn-acquisition/analysis.json`: E26c, with anti-alias before decimating.
- **Rows:** the balanced accuracy on the damaged bearings, per factor.

    uv run python papers/shared/figures/tab_guided_paderborn.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
E26 = ROOT / "experiments/E26-fault-order-guided-selector"
OUT = ROOT / "papers/mssp-2026/tables/tab_guided_paderborn.tex"
FACTORS = (1, 4, 8, 16, 32)


def load(name: str) -> dict:
    return json.loads((E26 / name / "analysis.json").read_text(encoding="utf-8"))["summary"]


def main() -> None:
    e26, e26b, e26c = (
        load("results-paderborn"),
        load("results-paderborn-rule"),
        load("results-paderborn-acquisition"),
    )
    rows = [
        ("pure decimation", "kurtogram band, blind order estimate", e26, "kurtogram|{f}x"),
        ("", "kurtogram band, fault-order rule", e26b, "kurtogram_rule|raw|{f}x"),
        ("", "wide band, fault-order rule", e26b, "wideband_rule|raw|{f}x"),
        ("", "guided band, fault-order rule", e26b, "guided|raw|{f}x"),
        (
            "anti-alias filter",
            "kurtogram band, fault-order rule",
            e26c,
            "antialias|kurtogram_rule|{f}x",
        ),
        ("", "wide band, fault-order rule", e26c, "antialias|wideband_rule|{f}x"),
        ("", "guided band, fault-order rule", e26c, "antialias|guided|{f}x"),
    ]
    cols = " & ".join(f"{f}$\\times$" for f in FACTORS)
    lines = [
        r"\begin{tabular}{ll" + "c" * len(FACTORS) + "}",
        r"\toprule",
        rf"acquisition & band and decision & {cols} \\",
        r"\midrule",
    ]
    for i, (acq, label, src, key) in enumerate(rows):
        if i == 4:
            lines.append(r"\midrule")
        cells = []
        for f in FACTORS:
            v = src.get(key.format(f=f))
            cells.append("--" if v is None or v.get("balanced") is None else f"{v['balanced']:.1f}")
        lines.append(f"{acq} & {label} & {' & '.join(cells)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    head = (
        "% generated by papers/shared/figures/tab_guided_paderborn.py from the analysis.json of\n"
        "% E26/E26b/E26c on Paderborn; do not edit by hand. Raw stream, balanced accuracy (%).\n"
    )
    OUT.write_text(head + "\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
